/* ==========================================================
   Service catalogue

   Single source of truth for the service sections on /services,
   their preview rows, and the per-service gallery routes at
   /services/:slug.

   MEDIA: comes from mediaManifest.json, generated by
   `npm run optimize:media` from the originals in media-src/. The
   manifest carries a small `thumb` for grid tiles and a larger `full`
   for the lightbox, plus intrinsic dimensions so tiles can reserve
   their space before the image arrives.

   This used to glob /public/services/** directly, which shipped the
   untouched camera originals — 40-60 megapixel stills and 42 MB
   videos — straight into tiles a few hundred pixels wide.

   No caption is derived from the filename. Gallery media is presented
   without visible titles, so labels here exist only for assistive
   tech and never render on screen.
   ========================================================== */

import manifest from './mediaManifest.json'

const buildMedia = (slug) =>
  (manifest[slug] || []).map((item, index) => ({
    ...item,
    /* Screen-reader only. Positional rather than descriptive because
       there is no trustworthy source of description — inventing one
       would be worse than a neutral label. */
    label: `${item.type === 'video' ? 'Video' : 'Photo'} ${index + 1}`
  }))

export const services = [
  {
    slug: 'digital-marketing',
    anchor: 'digital-marketing',
    titleKey: 'nav.digitalMarketing',
    descKey: 'services.items.social.desc',
    media: buildMedia('digital-marketing')
  },
  {
    slug: 'corporate-video',
    anchor: 'corporate-video',
    titleKey: 'nav.corporateVideo',
    descKey: 'services.items.corporate.desc',
    media: buildMedia('corporate-video')
  },
  {
    slug: 'photography',
    anchor: 'photography',
    titleKey: 'nav.photography',
    descKey: 'services.items.photography.desc',
    media: buildMedia('photography')
  },
  {
    slug: 'social-media',
    anchor: 'social-media',
    titleKey: 'nav.socialMedia',
    descKey: 'services.items.social.desc',
    media: buildMedia('social-media')
  }
]

export const getService = (slug) => services.find((s) => s.slug === slug)

